def main_results():
    paper = json.load(open(os.path.join(ROOT, "data", "reference", "base_paper_results.json")))["models"]
    body = []
    for m in ("Claude 3.5 Sonnet v2", "Qwen2.5-72B", "Llama 3.3 70B", "Mistral v0.3 7B"):
        v = paper[m]
        body.append("%s & reported & 300 & %.2f & -- & %.2f & %.2f" % (m, v["overall"], v["query"], v["action"]))
    body.append("\\midrule")
    runs = [("E0 Mistral-7B v0.3 (base-paper agent)", "e0_mistral_test20"),
            ("E1 Qwen2.5-7B single call", "e1_single_call_test50"),
            ("E2 Qwen2.5-7B base-paper agent", "e2_basepaper_test50"),
            ("E3 Qwen2.5-7B MedGuardian", "e3_medguardian_test50")]
    for label, run in runs:
        rows = load_csv(run + ".csv")
        if not rows:
            body.append("%s & reproduced & -- & -- & -- & -- & --" % label)
            continue
        k = sum(int(r["correct"]) for r in rows)
        lo, hi = wilson(k, len(rows))
        body.append("%s & reproduced & %d & %s & [%s, %s] & %s & %s" % (
            label, len(rows), fmt(sr(rows)), fmt(lo), fmt(hi), fmt(sr(rows, "query")), fmt(sr(rows, "action"))))
    e2, e3 = load_csv("e2_basepaper_test50.csv"), load_csv("e3_medguardian_test50.csv")
    if e2 and e3:
        b, c, p = mcnemar_exact(e2, e3)
        body.append("\\midrule")
        body.append("\\multicolumn{7}{l}{E2 vs E3, exact McNemar: %d tasks only E2 solved, %d only E3 solved, $p=%.3g$}"
                    % (b, c, p))
    table("main_results", "llrrcrr", "System & Source & $n$ & Overall SR & 95\\% CI & Query SR & Action SR", body,
          "success rates (%) of base-paper reported models vs our reproduced runs; CI = Wilson", wide=True)


def hypothesis_verdict(delta, target):
    if delta is None:
        return DASH
    return "Fully" if delta >= target else ("Partially" if delta > 0 else "Not")


def gap_resolution():
    e2, e3 = load_csv("e2_basepaper_test50.csv"), load_csv("e3_medguardian_test50.csv")
    g2, g3 = load_json("e4_g2_test_summary.json") or {}, load_json("e4_g3_test_summary.json") or {}
    rows = []
    a2, a3 = (sr(e2, "action") if e2 else None), (sr(e3, "action") if e3 else None)
    d1 = (a3 - a2) if a2 is not None and a3 is not None else None
    rows.append(["Gap 1: action reliability", "Typed FHIR tools, calculator, pre-order verifier",
                 "Action SR (%), test 50", "%s (E2, reproduced)" % fmt(a2), "%s (E3)" % fmt(a3),
                 hypothesis_verdict(d1, 15.0) + (" ($\\Delta$%s pp; H1: $\\geq$+15)" % fmt(d1) if d1 is not None else "")])
    gf, lf = (g2.get("guardian") or {}).get("f1"), (g2.get("llm_only") or {}).get("f1")
    d2 = (gf - lf) if gf is not None and lf is not None else None
    v2 = DASH if d2 is None else ("Fully" if gf >= 0.80 and d2 >= 0.15 else ("Partially" if d2 > 0 else "Not"))
    rows.append(["Gap 2: process guardian", "Timeline verifier + BM25 guideline retrieval",
                 "F1, 30 synthetic records", "not evaluated (LLM-only arm: %s)" % fmt(lf, 2), fmt(gf, 2),
                 v2 + (" (H2: F1$\\geq$0.80, $\\Delta\\geq$+0.15)" if d2 is not None else "")])
    ff = (g3.get("fused") or {}).get("f1")
    best_uni = max([x for x in ((g3.get("image_only") or {}).get("f1"), (g3.get("dictation_only") or {}).get("f1"))
                    if x is not None], default=None)
    d3 = (ff - best_uni) if ff is not None and best_uni is not None else None
    rows.append(["Gap 3: sonography fusion", "OCR + ASR + template-constrained fusion", "Field F1, 20 synthetic cases",
                 "not evaluated (best unimodal: %s)" % fmt(best_uni, 2), fmt(ff, 2),
                 (DASH if d3 is None else ("Fully" if d3 > 0 else "Not")) + (" (H3: fused $>$ both)" if d3 is not None else "")])
    table("gap_resolution", "p{2.2cm}p{3.2cm}p{2.3cm}p{2.6cm}p{1.4cm}p{3.0cm}",
          "Gap & Method / component & Metric & Base paper result & Our result & Addressed?",
          [" & ".join(r) for r in rows], "gap-resolution table required by the handout (same as README)", wide=True)
    md = ["| Gap | Method / component | Metric | Base paper result | Our result | Addressed? |", "|---|---|---|---|---|---|"]
    for r in rows:
        md.append("| " + " | ".join(x.replace("$\\geq$", ">=").replace("$\\Delta$", "Δ").replace("$\\Delta\\geq$", "Δ>=")
                                     .replace("$>$", ">").replace("\\", "") for x in r) + " |")
    os.makedirs(os.path.join(ROOT, "docs"), exist_ok=True)
    with open(os.path.join(ROOT, "docs", "gap_resolution.md"), "w") as fh:
        fh.write("<!-- Generated by experiments/make_tables.py from results/ -->\n" + "\n".join(md) + "\n")
    readme = os.path.join(ROOT, "README.md")
    text = open(readme).read()
    start, end = "<!-- GAP_TABLE_START -->", "<!-- GAP_TABLE_END -->"
    if start in text and end in text:
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        with open(readme, "w") as fh:
            fh.write(head + start + "\n" + "\n".join(md) + "\n" + end + tail)


def ablation():
    body = []
    full = load_csv("e3_medguardian_dev20.csv")
    for label, run in [("MedGuardian (all components)", "e3_medguardian_dev20"),
                       ("-- typed FHIR tools", "e5_no_typed_tools_dev20"),
                       ("-- calculator", "e5_no_calculator_dev20"),
                       ("-- order verifier", "e5_no_order_verifier_dev20"),
                       ("Base-paper agent (all off)", "e2_basepaper_dev20")]:
        rows = load_csv(run + ".csv")
        if rows:
            d = (sr(rows) - sr(full)) if full and run != "e3_medguardian_dev20" else None
            body.append("G1: %s & %s & %s & %s & %s" % (label, fmt(sr(rows)), fmt(sr(rows, "query")), fmt(sr(rows, "action")),
                                                       DASH if d is None else "%+.1f" % d))
        else:
            body.append("G1: %s & -- & -- & -- & --" % label)
    g2 = load_json("e4_g2_test_summary.json") or {}
    for arm, label in (("guardian", "timeline verifier + RAG"), ("llm_rag", "-- timeline verifier (LLM + RAG)"),
                       ("llm_only", "-- timeline verifier -- RAG (LLM only)")):
        s = g2.get(arm) or {}
        body.append("G2: %s & \\multicolumn{3}{c}{F1 %s, P %s, R %s} & --" % (label, fmt(s.get("f1"), 2),
                                                                            fmt(s.get("precision"), 2), fmt(s.get("recall"), 2)))
    gm = load_json("e4_g2_test_messy_summary.json") or {}
    for arm, label in (("guardian", "messy records: guardian"), ("llm_rag", "messy records: LLM + RAG"),
                       ("llm_only", "messy records: LLM only")):
        s = gm.get(arm) or {}
        body.append("G2: %s & \\multicolumn{3}{c}{F1 %s, P %s, R %s} & --" % (label, fmt(s.get("f1"), 2),
                                                                            fmt(s.get("precision"), 2), fmt(s.get("recall"), 2)))
    g3 = load_json("e4_g3_test_summary.json") or {}
    for arm, label in (("fused", "fused"), ("dictation_only", "-- image OCR (dictation only)"),
                       ("image_only", "-- dictation ASR (image only)")):
        s = g3.get(arm) or {}
        body.append("G3: %s & \\multicolumn{3}{c}{field F1 %s, BLEU-4 %s} & --" % (label, fmt(s.get("f1"), 2), fmt(s.get("bleu4"))))
    table("ablation", "lcccc", "Configuration & Overall SR & Query SR & Action SR & $\\Delta$ overall", body,
          "removing one component at a time; G1 on dev-20, G2/G3 on their test sets", wide=True)


def efficiency():
    body = []
    for label, run in [("E2 base-paper agent", "e2_basepaper_test50"), ("E3 MedGuardian", "e3_medguardian_test50")]:
        rows = load_csv(run + ".csv")
        if not rows:
            body.append("%s & -- & -- & -- & -- & -- & -- & --" % label)
            continue
        lat = sorted(float(r["latency_ms"]) / 1000 for r in rows)
        p95 = lat[min(len(lat) - 1, int(round(0.95 * (len(lat) - 1))))]
        tin = statistics.mean(int(r["tokens_in"]) for r in rows)
        tout = statistics.mean(int(r["tokens_out"]) for r in rows)
        rounds = statistics.mean(int(r["rounds"]) for r in rows)
        correct = sum(int(r["correct"]) for r in rows)
        gets = sum(int(r["n_get"]) for r in rows)
        bad = sum(r["status"] in ("agent invalid action", "task limit reached", "agent context limit") for r in rows)
        body.append("%s & %.0f & %.0f & %.0f & %.0f & %.2f & %s & %d/%d" % (
            label, statistics.median(lat), p95, tin, tout, rounds, fmt(gets / correct if correct else None, 1), bad, len(rows)))
    seeds = sorted(glob.glob(os.path.join(RES, "e6_t0.7_s*_dev10_summary.json")))
    if seeds:
        vals = [json.load(open(p))["overall_sr"] for p in seeds]
        body.append("\\midrule")
        body.append("\\multicolumn{8}{l}{E6 reliability, MedGuardian at $T{=}0.7$, %d seeds on dev-10: overall SR %.1f $\\pm$ %.1f}"
                    % (len(vals), statistics.mean(vals), statistics.stdev(vals) if len(vals) > 1 else 0.0))
    table("efficiency", "lccccccc", "System & s/task (p50) & s/task (p95) & tokens in & tokens out & rounds & GETs per correct & invalid/limit/overflow",
          body, "cost and reliability per task on the 50-task test split; Apple M4, Qwen2.5-7B Q4, zero API spend", wide=True)


def failures():
    body = []
    for run, label in (("e3_medguardian_test50", "E3 MedGuardian"), ("e2_basepaper_test50", "E2 base-paper agent")):
        s = load_json("failures_%s_summary.json" % run)
        if s:
            for k, v in s["counts"].items():
                body.append("%s & %s & %d & %.0f\\%%" % (label, k.replace("_", " "), v, 100.0 * v / s["n_failed"]))
            body.append("\\midrule")
    if body and body[-1] == "\\midrule":
        body.pop()
    table("failures", "llrr", "System & Failure category & Count & Share of failures", body or ["-- & -- & -- & --"],
          "auto-bucketed failure categories on the test split (experiments/failure_analysis.py)")


def numbers():
    """paper/tables/numbers.tex: one LaTeX macro per reportable number, so prose can cite results
    without typing them (\\EthreeActionSR etc.). Missing runs render as '--'."""
    m = {}
    names = {"Ezero": "e0_mistral_test20", "Eone": "e1_single_call_test50", "Etwo": "e2_basepaper_test50",
             "Ethree": "e3_medguardian_test50", "EthreeDev": "e3_medguardian_dev20", "EtwoDev": "e2_basepaper_dev20"}
    for mac, run in names.items():
        rows = load_csv(run + ".csv")
        k = sum(int(r["correct"]) for r in rows) if rows else None
        lo, hi = wilson(k, len(rows)) if rows else (None, None)
        m[mac + "N"] = str(len(rows)) if rows else DASH
        m[mac + "OverallSR"] = fmt(sr(rows)) if rows else DASH
        m[mac + "QuerySR"] = fmt(sr(rows, "query")) if rows else DASH
        m[mac + "ActionSR"] = fmt(sr(rows, "action")) if rows else DASH
        m[mac + "CILow"], m[mac + "CIHigh"] = fmt(lo), fmt(hi)
        if rows:
            m[mac + "TokensInPerTask"] = "%.0f" % statistics.mean(int(r["tokens_in"]) for r in rows)
            m[mac + "SecPerTask"] = "%.0f" % statistics.median(float(r["latency_ms"]) / 1000 for r in rows)
            m[mac + "RoundLimit"] = str(sum(r["status"] == "task limit reached" for r in rows))
            m[mac + "InvalidAction"] = str(sum(r["status"] == "agent invalid action" for r in rows))
            m[mac + "ContextLimit"] = str(sum(r["status"] == "agent context limit" for r in rows))
            if "n_post_rejected" in rows[0]:
                m[mac + "PostRejected"] = str(sum(int(r["n_post_rejected"] or 0) for r in rows))
                m[mac + "PostBlocked"] = str(sum(int(r["n_post_blocked"] or 0) for r in rows))
                m[mac + "FormatRepairs"] = str(sum(int(r["n_format_repairs"] or 0) for r in rows))
    e2, e3 = load_csv("e2_basepaper_test50.csv"), load_csv("e3_medguardian_test50.csv")
    if e2 and e3:
        b, c, p = mcnemar_exact(e2, e3)
        m.update({"McNemarOnlyEtwo": str(b), "McNemarOnlyEthree": str(c), "McNemarP": "%.3g" % p,
                  "ActionDeltaPP": "%+.1f" % (sr(e3, "action") - sr(e2, "action")),
                  "OverallDeltaPP": "%+.1f" % (sr(e3) - sr(e2))})
    for split, tag in (("test", "Gtwo"), ("test_messy", "GtwoMessy")):
        s = load_json("e4_g2_%s_summary.json" % split) or {}
        for arm, a in (("guardian", "Guardian"), ("llm_rag", "LLMRAG"), ("llm_only", "LLMOnly")):
            x = s.get(arm) or {}
            for metric, mm in (("f1", "Fone"), ("precision", "Prec"), ("recall", "Rec"),
                               ("false_alert_rate", "FalseAlert"), ("severity_weighted_miss_rate", "SevMiss")):
                m[tag + a + mm] = fmt(x.get(metric), 2)
    g3 = load_json("e4_g3_test_summary.json") or {}
    for arm, a in (("fused", "Fused"), ("image_only", "Image"), ("dictation_only", "Dictation")):
        x = g3.get(arm) or {}
        for metric, mm in (("f1", "Fone"), ("precision", "Prec"), ("recall", "Rec"),
                           ("measurement_error_rate", "MeasErr"), ("bleu4", "BLEU")):
            m["Gthree" + a + mm] = fmt(x.get(metric), 2) if metric != "bleu4" else fmt(x.get(metric), 1)
    m["GthreeConflictPrec"] = fmt((g3.get("fused") or {}).get("conflict_precision"), 2)
    m["GthreeConflictRec"] = fmt((g3.get("fused") or {}).get("conflict_recall"), 2)
    m["GthreeASRWER"] = fmt(100 * g3["asr_wer_mean"], 1) if g3.get("asr_wer_mean") is not None else DASH
    seeds = sorted(glob.glob(os.path.join(RES, "e6_t0.7_s*_dev10_summary.json")))
    if seeds:
        vals = [json.load(open(p))["overall_sr"] for p in seeds]
        m["EsixSeeds"] = str(len(vals))
        m["EsixMean"] = "%.1f" % statistics.mean(vals)
        m["EsixSD"] = "%.1f" % (statistics.stdev(vals) if len(vals) > 1 else 0.0)
    paper = json.load(open(os.path.join(ROOT, "data", "reference", "base_paper_results.json")))["models"]
    for name, mac in (("Claude 3.5 Sonnet v2", "PaperClaude"), ("Llama 3.3 70B", "PaperLlama"),
                      ("Qwen2.5-72B", "PaperQwenSeventyTwo"), ("Mistral v0.3 7B", "PaperMistral")):
        for k2, mm in (("overall", "Overall"), ("query", "Query"), ("action", "Action")):
            m[mac + mm] = "%.2f" % paper[name][k2]
    lines = ["% Generated by experiments/make_tables.py from results/ -- do not edit by hand."]
    for k in sorted(m):
        lines.append("\\newcommand{\\%s}{%s\\xspace}" % (k, m[k]))
    with open(os.path.join(OUT, "numbers.tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return m


