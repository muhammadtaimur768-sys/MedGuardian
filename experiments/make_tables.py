"""Generate every table in the paper (paper/tables/*.tex) and the README gap table from results/.

    python experiments/make_tables.py

No number is typed by hand: each cell is read from results/*.csv|json or
data/reference/base_paper_results.json. Missing runs render as "--" so the paper always compiles.
"""
import csv
import glob
import json
import math
import os
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "paper", "tables")
DASH = "--"


# -- helpers --------------------------------------------------------------------------------
def load_json(name):
    p = os.path.join(RES, name)
    return json.load(open(p)) if os.path.exists(p) else None


def load_csv(name):
    p = os.path.join(RES, name)
    return list(csv.DictReader(open(p))) if os.path.exists(p) else None


def fmt(x, nd=1):
    return DASH if x is None else ("%.*f" % (nd, x))


def wilson(k, n, z=1.96):
    if not n:
        return None, None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return 100 * (c - h), 100 * (c + h)


def mcnemar_exact(rows_a, rows_b):
    """Exact two-sided McNemar on paired task outcomes. Returns (b, c, p)."""
    a = {r["task_id"]: int(r["correct"]) for r in rows_a}
    b_ = {r["task_id"]: int(r["correct"]) for r in rows_b}
    common = sorted(set(a) & set(b_))
    b = sum(1 for t in common if a[t] == 1 and b_[t] == 0)
    c = sum(1 for t in common if a[t] == 0 and b_[t] == 1)
    n = b + c
    if n == 0:
        return b, c, 1.0
    tail = sum(math.comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n
    return b, c, min(1.0, 2 * tail)


def sr(rows, kind=None):
    rs = [r for r in rows if kind is None or r["kind"] == kind]
    return (100.0 * sum(int(r["correct"]) for r in rs) / len(rs)) if rs else None


def table(name, colspec, header, body, caption_hint, wide=False, label=None):
    env = "table*" if wide else "table"
    lines = ["%% Generated by experiments/make_tables.py from results/ -- do not edit by hand.",
             "\\begin{%s}[t]" % env, "\\centering", "\\small",
             "\\caption{%s}" % (caption_hint[0].upper() + caption_hint[1:]).replace("%", "\\%"),
             "\\label{tab:%s}" % (label or name), "\\begin{tabular}{%s}" % colspec, "\\toprule", header + " \\\\",
             "\\midrule"] + [r if r.startswith("\\midrule") else r + " \\\\" for r in body] + \
        ["\\bottomrule", "\\end{tabular}", "\\end{%s}" % env]
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".tex"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


