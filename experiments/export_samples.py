"""Export representative trajectories to logs/samples/ (committed; full logs are git-ignored).

    python experiments/export_samples.py

Picks, from the E3 MedGuardian test run (and E2 for contrast):
  success_repaired      verifier rejected a draft order, the repaired order passed, task correct
  success_blocked       verifier blocked an unindicated order, task correct
  success_query         a correct query task
  failure_<category>    one failed task for each of the two most frequent failure categories
  e2_failure_same_task  E2's trajectory on the same task as one E3 success (before/after)
Each sample is a readable JSON file with the task, the model conversation, what was sent to the EHR,
and the grader outcome; logs/samples/README.md lists them.
"""
import collections
import csv
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "logs", "samples")


def load_ends(run):
    ends = {}
    for line in open(os.path.join(ROOT, "logs", run + ".jsonl")):
        e = json.loads(line)
        if e["event"] == "task_end":
            ends[e["task_id"]] = e
    return ends


def write(name, rec, why):
    os.makedirs(OUT, exist_ok=True)
    keep = {k: rec.get(k) for k in ("run_id", "task_id", "category", "kind", "status", "correct", "result", "rounds",
                                     "n_get", "n_post", "n_post_rejected", "n_post_blocked", "grader_stdout")}
    keep["why_selected"] = why
    keep["model_conversation"] = rec.get("conversation") or rec.get("history")
    keep["sent_to_ehr"] = rec.get("history")
    with open(os.path.join(OUT, name + ".json"), "w") as fh:
        json.dump(keep, fh, indent=2, ensure_ascii=False)
    return name, rec["task_id"], why


def main():
    e3, e2 = load_ends("e3_medguardian_test50"), load_ends("e2_basepaper_test50")
    picked = []

    def first(pred):
        return next((r for r in e3.values() if pred(r)), None)

    r = first(lambda r: r["correct"] and r.get("n_post_rejected", 0) and not r.get("n_post_blocked", 0))
    if r:
        picked.append(write("success_repaired", r, "verifier rejected a draft, the repaired order passed"))
    r = first(lambda r: r["correct"] and r.get("n_post_blocked", 0))
    if r:
        picked.append(write("success_blocked", r, "verifier blocked an order that was not indicated"))
    r = first(lambda r: r["correct"] and r["kind"] == "query" and r["rounds"] >= 2)
    if r:
        picked.append(write("success_query", r, "correct query task"))
        if r["task_id"] in e2:
            picked.append(write("e2_same_task_as_success_query", e2[r["task_id"]],
                                "base-paper agent on the same task, for contrast"))
    fpath = os.path.join(ROOT, "results", "failures_e3_medguardian_test50.csv")
    if os.path.exists(fpath):
        rows = list(csv.DictReader(open(fpath)))
        for cat, _ in collections.Counter(x["failure"] for x in rows).most_common(2):
            tid = next(x["task_id"] for x in rows if x["failure"] == cat)
            picked.append(write("failure_" + cat, e3[tid], "most frequent failure category: " + cat))
    with open(os.path.join(OUT, "README.md"), "w") as fh:
        fh.write("# Representative trajectories (generated by experiments/export_samples.py)\n\n"
                 "| File | Task | Why selected |\n|---|---|---|\n")
        for name, tid, why in picked:
            fh.write("| `%s.json` | %s | %s |\n" % (name, tid, why))
    print("\n".join("%s %s" % (n, t) for n, t, _ in picked))


if __name__ == "__main__":
    main()
